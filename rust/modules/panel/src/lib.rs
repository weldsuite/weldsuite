//! WeldPanel (product analytics): panel-api's project routes
//! (`apps/workers/panel-api`, `/api/panel/projects`) and the public collector
//! panel-ingest serves on Global (`apps/workers/panel-ingest`: the SDK and
//! its plugins, `/c/:token`, `POST /e`, `/r`, `/snap`, `/v1/track` and
//! `/v1/import`), with `@weldsuite/panel-domain`'s rules.
//!
//! The tenant `panel_projects` row is the source of truth. Every change
//! also writes the master `panel_project_registry` row and the cache record
//! `panel:project:<token>` the collector reads ([`registry`]); the collector
//! never opens a tenant database (ADR DATA-008).
//!
//! What Cloudflare gives panel-ingest, and what it is here ([`collector`]):
//!
//! - the events stream (a Pipelines binding feeding the Basin table
//!   `panel.events_v1`): one message per row on a `JetStream` stream, subject
//!   `panel.events.v1.<workspace>`, through [`EventSink`];
//! - the recording chunk index (the stream behind `panel.replay_chunks_v1`):
//!   subject `panel.replays.v1.<workspace>` of the `PANEL_STATE` stream,
//!   also an [`EventSink`];
//! - the private EU replays bucket (recording chunks and heatmap
//!   snapshots): the install's panel bucket (`S3_BUCKET_PANEL`), the same keys,
//!   recordings under `replays/` ([`PanelBucketReplays`]);
//! - `PanelSalt`, the global Durable Object holding each UTC day's random
//!   salt of the cookieless visitor hash: the cache (Valkey), the salt
//!   claimed by the first pod that needs it and kept two days ([`SaltSource`]);
//! - `PanelUsage`, events and recordings counted per workspace and UTC day:
//!   atomic counters in the cache ([`UsageCounter`]), settled by
//!   `weldsuite cron panel-usage` ([`usage_sweep`]) where the object's alarm
//!   settled them;
//! - the per-IP rate-limiting bindings: counters in the cache
//!   ([`RateLimiter`]);
//! - KV: the cache. The cache is not durable storage, so a project or
//!   secret key record missing from it is read from the master registry and
//!   put back. The quota state (`panel:quota:<workspace>`) is read from the
//!   cache, where the usage settlement writes it.
//!
//! Reports (`/api/panel/query`, `/api/panel/lexicon`) compile a typed spec
//! with `weldsuite-panel-domain` and run it on the analytics engine
//! ([`AnalyticsSql`]: DataFusion over the install's Iceberg tables, ADR
//! EVT-019), with what Global keeps in the `PanelProject` Durable Object
//! behind [`PanelProjectState`]. Bodies are validated with panel-api's own
//! Zod schemas ([`weldsuite_zod`], `schemas_gen.rs` generated by
//! `tools/generate.mts`, refinements in `hooks.rs`).
//!
//! People (with GDPR erasure, [`erasure`]), groups, sessions and recordings,
//! heatmap page groups and snapshots, and the live view
//! ([`people_router`] and its siblings) read profiles and the live view from
//! the same [`PanelProjectState`], activity from the analytics engine, and
//! recording chunks and snapshots from the replays bucket
//! ([`PanelState::replays`]). An erasure waits for the table rewrite in the
//! master `panel_erasure_ledger` ([`MasterErasureLedger`]).
//!
//! Root cause and metric tree values ([`insights_router`],
//! [`metric_tree_values_router`]) run on the same engine; AI summaries of
//! recordings and root-cause narratives on the install's AI
//! ([`PanelState::ai`], Mistral on EU), metered on the credit wallet. Usage
//! ([`usage_router`]) settles the month's overage where the install bills
//! plans ([`PanelState::bill_overage`], [`usage_settlement`]) and mails the
//! owners the notice that is due ([`usage_mail`]). The internal read API
//! ([`internal_v1_router`]) hands the platform's read handlers to in-process
//! callers; the internal settlement route ([`internal_usage_router`]) is
//! served in conformance builds only, as the job settles in process.
//!
//! Paths, bodies, status codes, messages and side effects are the
//! TypeScript workers'; their tests run against this crate in the `panel`
//! conformance suites (`rust/conformance/suites.json`).

