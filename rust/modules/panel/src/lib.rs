/// Who is asking, in which workspace, with what the request brings.
pub(crate) struct Caller {
    pub(crate) db: PgPool,
    pub(crate) user_id: String,
    /// `c.get('workspaceId')`: `workspaces.id`; empty without one.
    pub(crate) workspace_id: String,
    /// The Clerk org id (`c.get('clerkOrgId')`): the hub in-app notifications go to.
    pub(crate) clerk_org_id: Option<String>,
    pub(crate) events: EventContext,
    env: Option<RequestEnv>,
    cache: Option<Arc<dyn DynCache>>,
    master: Option<PgPool>,
    headers: HeaderMap,
    /// The request's outbound HTTP (conformance: the harness's bridge).
    outbound: Option<OutboundHttp>,
    /// The request's project state (conformance: the test's `PANEL_PROJECT`).
    project_state: Option<RequestProjectState>,
    /// The request's AI (conformance: on with the test's mock model, off
    /// without it).
    ai: Option<weldsuite_ai::Ai>,
}

impl Caller {
    /// The analytics engine: the test's Basin (`R2_SQL_API_TOKEN`,
    /// `CF_ACCOUNT_ID`, `PANEL_BASIN_BUCKET`, through the outbound bridge)
    /// in conformance, else the state's. `None` is not configured here.
    pub(crate) fn analytics(&self, state: &PanelState) -> Option<Arc<dyn AnalyticsSql>> {
        if self.conformance() {
            let token = self.env("R2_SQL_API_TOKEN")?;
            let account_id = self.env("CF_ACCOUNT_ID")?;
            let bucket = self.env("PANEL_BASIN_BUCKET")?;
            let http = self.outbound.clone()?;
            return Some(Arc::new(BasinSql::new(http, token, account_id, bucket)));
        }
        state.sql.clone()
    }

    /// The AI a call runs on: the request's (conformance), then the
    /// state's; `None` when it is off.
    pub(crate) fn ai(&self, state: &PanelState) -> Option<weldsuite_ai::Ai> {
        self.ai
            .as_ref()
            .or(state.ai.as_ref())
            .filter(|ai| ai.enabled())
            .cloned()
    }

    /// `c.env.PANEL_PROJECT`: the test's (conformance), else the state's.
    pub(crate) fn project_state(&self, state: &PanelState) -> Option<Arc<dyn PanelProjectState>> {
        if self.conformance() {
            return self.project_state.as_ref().and_then(|s| s.0.clone());
        }
        state.project_state.clone()
    }

    /// The test's clock when it fakes one (`CONFORMANCE_NOW`, which only the
    /// harness sets), else `None` (the real clock).
    pub(crate) fn now(&self) -> Option<i64> {
        if !self.conformance() {
            return None;
        }
        self.env("CONFORMANCE_NOW")
            .and_then(|now| weldsuite_panel_domain::js::parse_iso(&now))
    }

    /// `publishEntityEvent({ c, entityType, action, entityId, data })`.
    pub(crate) fn publish(
        &self,
        state: &PanelState,
        event: EventName,
        entity_id: &str,
        data: &Value,
    ) {
        publish_entity_event(&state.events, &self.events, event, entity_id, data);
    }

    fn conformance(&self) -> bool {
        self.env.is_some()
    }

    /// `c.env.<name>`: the test's (conformance), else the process's.
    pub(crate) fn env(&self, name: &str) -> Option<String> {
        match &self.env {
            Some(env) => env.get(name).map(str::to_owned),
            None => std::env::var(name).ok(),
        }
        .filter(|value| !value.is_empty())
    }

    /// `c.env.WORKSPACE_CACHE`: the test's KV (conformance), else the state's.
    pub(crate) fn cache(&self, state: &PanelState) -> Option<Arc<dyn DynCache>> {
        if self.conformance() {
            return self.cache.clone();
        }
        state.cache.clone()
    }

    /// `getMasterDb(c.env)`: the test's (conformance), else the state's.
    pub(crate) fn master(&self, state: &PanelState) -> Option<PgPool> {
        if self.conformance() {
            return self.master.clone();
        }
        state.master.clone()
    }

    /// `c.env.PANEL_COLLECTOR_URL`; on Kubernetes, without one, the origin
    /// the request came to (as the ingress forwarded it), which serves the
    /// collector at its root too.
    pub(crate) fn collector_url(&self, state: &PanelState) -> Option<String> {
        if self.conformance() {
            return self.env("PANEL_COLLECTOR_URL");
        }
        state
            .collector_url
            .clone()
            .or_else(|| request_origin(&self.headers))
    }
}

/// `https://<host>` of the request as the ingress forwarded it.
pub(crate) fn request_origin(headers: &HeaderMap) -> Option<String> {
    let first = |name: &str| {
        headers
            .get(name)
            .and_then(|value| value.to_str().ok())
            .and_then(|value| value.split(',').next())
            .map(str::trim)
            .filter(|value| !value.is_empty())
    };
    let host = first("x-forwarded-host").or_else(|| first("host"))?;
    if !host
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | ':' | '[' | ']'))
    {
        return None;
    }
    let scheme = match first("x-forwarded-proto") {
        Some(proto) if proto.eq_ignore_ascii_case("http") => "http",
        _ => "https",
    };
    Some(format!("{scheme}://{host}"))
}

/// Behind the session and tenant database layers; without them it is a
/// routing mistake (500).
impl<S: Send + Sync> FromRequestParts<S> for Caller {
    type Rejection = ApiError;

    fn from_request_parts(
        parts: &mut Parts,
        _state: &S,
    ) -> impl Future<Output = Result<Self, Self::Rejection>> + Send {
        let extensions = &parts.extensions;
        let caller = if let (Some(auth), Some(tenant)) =
            (extensions.get::<AuthContext>(), extensions.get::<Tenant>())
        {
            Ok(Self {
                db: tenant.db.clone(),
                user_id: auth.user_id.clone(),
                workspace_id: tenant.workspace_id.clone(),
                clerk_org_id: tenant.clerk_org_id.clone(),
                events: EventContext::for_request(auth, tenant),
                env: extensions.get::<RequestEnv>().cloned(),
                cache: extensions
                    .get::<RequestCache>()
                    .map(|cache| Arc::clone(&cache.0)),
                master: extensions.get::<MasterDb>().map(|master| master.0.clone()),
                headers: parts.headers.clone(),
                outbound: extensions.get::<OutboundHttp>().cloned(),
                project_state: extensions.get::<RequestProjectState>().cloned(),
                ai: extensions.get::<weldsuite_ai::Ai>().cloned(),
            })
        } else {
            tracing::error!("panel: a route without the session or tenant layer");
            Err(ApiError::internal())
        };
        std::future::ready(caller)
    }
}

/// `zValidator('json', schema)`: the body read by `read`, or the 400 (bad
/// JSON, or the schema's issues).
pub(crate) fn validate<T>(
    headers: &HeaderMap,
    body: &Bytes,
    read: impl FnOnce(&mut Issues, &Map<String, Value>) -> T,
) -> Result<T, Box<Response>> {
    let content_type = headers
        .get(CONTENT_TYPE)
        .and_then(|value| value.to_str().ok());
    let body = json_body(content_type, body).map_err(|bad| Box::new(bad.into_response()))?;
    let mut issues = Issues::default();
    let value = issues.object(&body).map(|fields| read(&mut issues, fields));
    issues
        .finish()
        .map_err(|invalid| Box::new(invalid.into_response()))?;
    value.ok_or_else(|| Box::new(ApiError::internal().into_response()))
}

/// What the worker's `onError` answers for anything a route throws.
pub(crate) fn unexpected(error: &dyn std::fmt::Display, what: &str) -> Response {
    tracing::error!(%error, "[panel-api] {what}");
    ApiError::internal()
        .with_message("An unexpected error occurred")
        .into_response()
}
