/// What the project routes share.
#[derive(Clone)]
pub struct PanelState {
    pub events: EntityEventPublisher,
    /// The cache the collector reads (`WORKSPACE_CACHE` on Global). A
    /// request's `RequestCache` (conformance) wins.
    pub cache: Option<Arc<dyn DynCache>>,
    /// The master database (`panel_project_registry`). A request's
    /// `MasterDb` (conformance) wins.
    pub master: Option<PgPool>,
    /// `PANEL_COLLECTOR_URL`: the collector origin the install snippets
    /// point at; else the origin the request came to, where this server
    /// serves the collector too.
    pub collector_url: Option<String>,
    /// The analytics engine the reports run on: DataFusion over the panel
    /// store, `None` on an install without one (queries answer 503).
    /// Conformance builds use the test's Basin instead.
    pub sql: Option<Arc<dyn AnalyticsSql>>,
    /// What Global keeps in the `PanelProject` Durable Object. `None`:
    /// queries answer 503, as panel-api without `PANEL_PROJECT`. A
    /// request's [`RequestProjectState`] (conformance) wins.
    pub project_state: Option<Arc<dyn PanelProjectState>>,
    /// Global's replays bucket (recording chunks, heatmap snapshots) in the
    /// panel bucket ([`PanelBucketReplays`]); `None` without one, where
    /// there are no recordings. A request's bucket (conformance) wins.
    pub replays: Option<Arc<dyn weldsuite_ports::DynFileStore>>,
    /// In-app notifications (`REALTIME`): a comment's target owner is told.
    pub realtime: Option<Arc<dyn DynRealtimePublisher>>,
    /// Opens the workspace behind a public share link. A request's
    /// [`RequestWorkspaceTenants`] (conformance) wins.
    pub tenants: Option<Arc<dyn WorkspaceTenants>>,
    /// Proxies in front of the server (`TRUSTED_PROXIES`): which
    /// `X-Forwarded-For` entry is the visitor of a public link.
    pub trusted_proxies: usize,
    /// The install's AI (`weldsuite_ai`, Mistral on EU): AI summaries and
    /// root-cause narratives. `None` (or off) answers as panel-api without
    /// its gateway. A request's own (conformance) wins.
    pub ai: Option<weldsuite_ai::Ai>,
    /// The install bills plans (`billing`): overage is charged to the
    /// credit wallet and an unpaid block blocks the collector. Without it
    /// nothing is charged and the quota stays `ok`.
    pub bill_overage: bool,
    /// The install's system mail: the usage notices to a workspace's owners
    /// ([`usage_mail`]). `None` sends none, as panel-api without a mail
    /// binding.
    pub mail: Option<Arc<dyn DynSystemMail>>,
}

impl std::fmt::Debug for PanelState {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("PanelState")
            .field("events", &self.events)
            .field("cache", &self.cache.is_some())
            .field("master", &self.master.is_some())
            .field("collector_url", &self.collector_url)
            .field("sql", &self.sql.is_some())
            .field("project_state", &self.project_state.is_some())
            .field("replays", &self.replays.is_some())
            .field("realtime", &self.realtime.is_some())
            .field("tenants", &self.tenants.is_some())
            .field("trusted_proxies", &self.trusted_proxies)
            .field("ai", &self.ai.is_some())
            .field("bill_overage", &self.bill_overage)
            .field("mail", &self.mail.is_some())
            .finish()
    }
}

/// `/api/panel/projects`, relative to `/api/panel/projects`, behind the
/// session, tenant database, licence and flag layers.
pub fn router<S, Q>(state: PanelState, gate: &Arc<PermissionGate<Q>>) -> Router<S>
where
    S: Clone + Send + Sync + 'static,
    Q: PermissionQueries + 'static,
{
    let read = || gate.require([PANEL_PROJECTS_READ]);
    let manage = || gate.require([PANEL_PROJECTS_MANAGE]);
    Router::new()
        .route("/", get(projects::list).route_layer(read()))
        .route(
            "/",
            post(projects::create).route_layer(gate.require([PANEL_PROJECTS_CREATE])),
        )
        .route("/{id}", get(projects::detail).route_layer(read()))
        .route(
            "/{id}",
            patch(projects::update).route_layer(gate.require([PANEL_PROJECTS_UPDATE])),
        )
        .route(
            "/{id}",
            axum::routing::delete(projects::remove)
                .route_layer(gate.require([PANEL_PROJECTS_DELETE])),
        )
        .route(
            "/{id}/settings",
            patch(projects::update_settings).route_layer(manage()),
        )
        .route(
            "/{id}/rotate-token",
            post(projects::rotate_token).route_layer(manage()),
        )
        .route("/{id}/install", get(projects::install).route_layer(read()))
        // Secret keys sit under their project (`routes/keys`).
        .route(
            "/{id}/keys",
            get(keys::list).post(keys::create).route_layer(manage()),
        )
        .route(
            "/{id}/keys/{key_id}",
            axum::routing::delete(keys::revoke).route_layer(manage()),
        )
        .with_state(state)
}

/// `/api/panel/query`, relative to `/api/panel/query`, behind the same
/// layers as [`router`].
pub fn query_router<S, Q>(state: PanelState, gate: &Arc<PermissionGate<Q>>) -> Router<S>
where
    S: Clone + Send + Sync + 'static,
    Q: PermissionQueries + 'static,
{
    Router::new()
        .route(
            "/",
            post(query::run).route_layer(gate.require([PANEL_REPORTS_READ])),
        )
        .with_state(state)
}

