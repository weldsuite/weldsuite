//! The US states the sales tax reads (`@weldsuite/books-domain/jurisdictions/us/states`:
//! names, whether they tax, intrastate sourcing, certificate validity rules),
//! generated from the TypeScript table. Every state rounds per jurisdiction
//! on the invoice.

#![allow(clippy::doc_markdown)]

/// A certificate validity rule (`CertificateValidityRule`).
#[derive(Debug, Clone, Copy)]
pub(crate) struct CertificateRule {
    pub(crate) reasons: Option<&'static [&'static str]>,
    pub(crate) forms: Option<&'static [&'static str]>,
    pub(crate) blanket_only: bool,
    pub(crate) expiry: Expiry,
}

/// When a certificate expires.
#[derive(Debug, Clone, Copy)]
pub(crate) enum Expiry {
    CalendarYearEnd,
    MonthsFromIssue(i64),
    MonthsFromLastPurchase(i64),
}

/// A state (`UsStateInfo`).
#[derive(Debug, Clone, Copy)]
pub(crate) struct UsState {
    pub(crate) code: &'static str,
    pub(crate) name: &'static str,
    pub(crate) state_tax: bool,
    pub(crate) local_tax: bool,
    pub(crate) sourcing: &'static str,
    pub(crate) certificates: &'static [CertificateRule],
}

