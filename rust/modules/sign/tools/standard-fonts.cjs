// Writes rust/modules/sign/src/standard_fonts.rs: the WinAnsi encoding and
// the glyph widths and kerning of the three standard fonts the signed PDF
// uses, from @pdf-lib/standard-fonts (what pdf-lib measures text with).
//
//   node rust/modules/sign/tools/standard-fonts.cjs
const { createRequire } = require('node:module');
const { writeFileSync } = require('node:fs');
const path = require('node:path');

const repo = path.resolve(__dirname, '../../../..');
const fromSign = createRequire(path.join(repo, 'packages/domains/sign/package.json'));
const fromPdfLib = createRequire(fromSign.resolve('pdf-lib'));
const { Font, FontNames, Encodings } = fromPdfLib('@pdf-lib/standard-fonts');

const encoding = Encodings.WinAnsi;
const codes = [];
for (let cp = 0; cp < 0x10000; cp++) {
  try {
    const { code, name } = encoding.encodeUnicodeCodePoint(cp);
    codes.push({ cp, code, name });
  } catch {
    // Not in WinAnsi.
  }
}
const byCode = new Map();
for (const c of codes) if (!byCode.has(c.code)) byCode.set(c.code, c.name);

function fontTables(fontName, ident) {
  const font = Font.load(fontName);
  const widths = new Array(256).fill(0);
  for (const [code, name] of byCode) widths[code] = font.getWidthOfGlyph(name) ?? 0;
  const kerns = [];
  for (const [l, ln] of byCode) {
    for (const [r, rn] of byCode) {
      const k = font.getXAxisKerningForPair(ln, rn);
      if (k) kerns.push([l, r, k]);
    }
  }
  kerns.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  return (
    `/// ${font.FontName}: ascender, descender, widths by WinAnsi code, kerning pairs (sorted).\n` +
    `pub(crate) const ${ident}: StandardFont = StandardFont {\n` +
    `    base_font: "${font.FontName}",\n` +
    `    ascender: ${font.Ascender ?? font.FontBBox[3]},\n` +
    `    descender: ${font.Descender ?? font.FontBBox[1]},\n` +
    `    widths: &[${widths.join(', ')}],\n` +
    `    kerning: &[${kerns.map(([l, r, k]) => `(${l}, ${r}, ${k})`).join(', ')}],\n` +
    `};\n`
  );
}

const out =
  `//! Generated by \`node rust/modules/sign/tools/standard-fonts.cjs\` from\n` +
  `//! @pdf-lib/standard-fonts; don't edit. The WinAnsi encoding and the metrics\n` +
  `//! pdf-lib measures standard-font text with.\n\n` +
  `#![allow(clippy::unreadable_literal)]\n\n` +
  `/// A standard (base 14) font's metrics, by WinAnsi code.\n` +
  `pub(crate) struct StandardFont {\n` +
  `    pub(crate) base_font: &'static str,\n` +
  `    pub(crate) ascender: i32,\n` +
  `    pub(crate) descender: i32,\n` +
  `    pub(crate) widths: &'static [u16],\n` +
  `    pub(crate) kerning: &'static [(u8, u8, i16)],\n` +
  `}\n\n` +
  `/// Unicode code point → WinAnsi code, sorted by code point.\n` +
  `pub(crate) const WIN_ANSI: &[(u32, u8)] = &[${codes.map((c) => `(${c.cp}, ${c.code})`).join(', ')}];\n\n` +
  fontTables(FontNames.Helvetica, 'HELVETICA') +
  '\n' +
  fontTables(FontNames.HelveticaBold, 'HELVETICA_BOLD') +
  '\n' +
  fontTables(FontNames.Courier, 'COURIER');

writeFileSync(path.join(repo, 'rust/modules/sign/src/standard_fonts.rs'), out);
console.log(`WinAnsi: ${codes.length} code points`);
