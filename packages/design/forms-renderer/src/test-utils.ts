export function makeDefinition(input: Partial<FormDefinitionInput> & Pick<FormDefinitionInput, 'blocks'>): FormDefinition {
  return formDefinitionSchema.parse({
    endings: [{ id: 'e_done', ref: 'done', title: 'Thanks {{field:name}}' }],
    ...input,
  });
}

