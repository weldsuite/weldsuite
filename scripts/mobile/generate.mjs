#!/usr/bin/env node
/**
 * Writes what the native apps (`apps/ios`, `apps/android`) read from
 * `apps/mobile-shared`:
 *
 * - strings: `strings/<source>/{en,nl}.json` → `Localizable.xcstrings` plus a
 *   typed Swift accessor per iOS bundle, and `values/strings.xml` plus
 *   `values-nl/strings.xml` per Android module;
 * - tokens: `tokens.json` → `Tokens.swift` (WeldUI) and `Tokens.kt` (`:ui`);
 * - OpenAPI: `openapi/<module>.yaml` → a copy inside each Swift target that
 *   swift-openapi-generator builds from (Android's Gradle reads the originals).
 *
 * `--check` writes nothing and exits 1 when a generated file is missing or
 * stale; CI runs it in the iOS and Android jobs.
 *
 * Strings: nested keys flatten to dot paths (`items.offlineBanner`). `{name}`
 * placeholders become positional format arguments in order of first
 * appearance; `count`, `bits`, `healthy` and `checked` are integers, the rest
 * strings. An object with only `zero/one/two/few/many/other` keys is a plural
 * on `{count}`.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SHARED = join(ROOT, 'apps/mobile-shared');
const LOCALES = ['en', 'nl'];
const SOURCE_LOCALE = 'en';
const INTEGER_PLACEHOLDERS = new Set(['count', 'bits', 'healthy', 'checked']);
const PLURAL_KEYS = new Set(['zero', 'one', 'two', 'few', 'many', 'other']);
const BANNER = 'Generated by scripts/mobile/generate.mjs from apps/mobile-shared. Do not edit.';

/**
 * Each string source, where its output goes on each platform. `prefix` names
 * the Android resources (`core_sign_in_button`), so a library's strings and
 * an app's never collide when Gradle merges them.
 */
const STRING_SOURCES = [
  {
    source: 'core',
    ios: {
      catalog: 'apps/ios/WeldKit/Sources/WeldCore/Resources/Localizable.xcstrings',
      accessor: 'apps/ios/WeldKit/Sources/WeldCore/Generated/CoreStrings.swift',
      enumName: 'CoreStrings',
      bundle: '.module',
      access: 'public ',
    },
    android: { res: 'apps/android/core/src/main/res', prefix: 'core' },
  },
  {
    source: 'weldpass',
    ios: {
      catalog: 'apps/ios/Apps/WeldPass/Resources/Localizable.xcstrings',
      accessor: 'apps/ios/Apps/WeldPass/Sources/Generated/PassStrings.swift',
      enumName: 'PassStrings',
      bundle: '.main',
      access: '',
    },
    android: { res: 'apps/android/apps/weldpass/src/main/res', prefix: 'weldpass' },
  },
];

const OPENAPI_COPIES = [
  { from: 'openapi/core.yaml', to: 'apps/ios/WeldKit/Sources/CoreAPI/openapi.yaml' },
  { from: 'openapi/weldpass.yaml', to: 'apps/ios/WeldKit/Sources/WeldPassAPI/openapi.yaml' },
];

// ── strings ──────────────────────────────────────────────────────────────────

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function isPlural(value) {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const keys = Object.keys(value);
  return keys.length > 0 && keys.includes('other') && keys.every((key) => PLURAL_KEYS.has(key));
}

/** `{ items: { title: 'x' } }` → `Map('items.title' → 'x')`, plurals kept as objects. */
function flatten(tree, prefix = '', out = new Map()) {
  for (const [key, value] of Object.entries(tree)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === 'string' || isPlural(value)) out.set(path, value);
    else if (typeof value === 'object' && value !== null) flatten(value, path, out);
    else throw new Error(`${path}: expected a string, a plural or an object`);
  }
  return out;
}

function placeholdersOf(text) {
  const names = [];
  for (const match of text.matchAll(/\{([A-Za-z][A-Za-z0-9]*)\}/g)) {
    if (!names.includes(match[1])) names.push(match[1]);
  }
  return names;
}

/** Placeholder names of a string or every variant of a plural, in order of first appearance. */
function argumentsOf(value) {
  if (typeof value === 'string') return placeholdersOf(value);
  const names = [];
  for (const variant of Object.values(value)) {
    for (const name of placeholdersOf(variant)) if (!names.includes(name)) names.push(name);
  }
  return names;
}

/** Code-unit order, the same as `sort()` without a compare function, spelled out. */
function compareText(a, b) {
  if (a < b) return -1;
  return a > b ? 1 : 0;
}

function sortedKeys(map) {
  return [...map.keys()].sort(compareText);
}

/** What's wrong with one locale's table against the source locale's. */
function localeProblems(source, locale, base, table) {
  const problems = [];
  for (const key of base.keys()) if (!table.has(key)) problems.push(`${source}/${locale}.json lacks ${key}`);
  for (const key of table.keys()) if (!base.has(key)) problems.push(`${source}/${locale}.json has ${key}, which en.json lacks`);
  for (const [key, value] of base) {
    const other = table.get(key);
    if (other === undefined) continue;
    if (isPlural(value) !== isPlural(other)) problems.push(`${source}: ${key} is a plural in one locale only`);
    const a = argumentsOf(value).sort(compareText).join(',');
    const b = argumentsOf(other).sort(compareText).join(',');
    if (a !== b) problems.push(`${source}: ${key} has placeholders {${a}} in en, {${b}} in ${locale}`);
  }
  return problems;
}

function loadSource(source) {
  const tables = new Map();
  for (const locale of LOCALES) {
    tables.set(locale, flatten(readJson(join(SHARED, 'strings', source, `${locale}.json`))));
  }
  const base = tables.get(SOURCE_LOCALE);
  const problems = LOCALES.filter((locale) => locale !== SOURCE_LOCALE).flatMap((locale) =>
    localeProblems(source, locale, base, tables.get(locale)),
  );
  for (const [key, value] of base) {
    if (isPlural(value) && argumentsOf(value).some((name) => name !== 'count')) {
      problems.push(`${source}: plural ${key} may only use {count}`);
    }
  }
  if (problems.length > 0) throw new Error(problems.join('\n'));
  return { base, tables };
}

/** The placeholder order of a key, taken from the source locale so every locale agrees. */
function orderFor(base, key) {
  return argumentsOf(base.get(key));
}

// iOS ─────────────────────────────────────────────────────────────────────────

/** A string with arguments goes through `String(format:)`, so its own `%` is doubled. */
function iosFormat(text, order, plural) {
  const formatted = plural || order.length > 0;
  return (formatted ? text.replaceAll('%', '%%') : text).replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_, name) => {
    const spec = INTEGER_PLACEHOLDERS.has(name) ? 'lld' : '@';
    if (plural || order.length === 1) return `%${spec}`;
    return `%${order.indexOf(name) + 1}$${spec}`;
  });
}

function xcstrings({ base, tables }) {
  const strings = {};
  for (const key of sortedKeys(base)) {
    const order = orderFor(base, key);
    const localizations = {};
    for (const locale of LOCALES) {
      const value = tables.get(locale).get(key);
      if (typeof value === 'string') {
        localizations[locale] = { stringUnit: { state: 'translated', value: iosFormat(value, order, false) } };
      } else {
        const plural = {};
        for (const [quantity, text] of Object.entries(value)) {
          plural[quantity] = { stringUnit: { state: 'translated', value: iosFormat(text, order, true) } };
        }
        localizations[locale] = { variations: { plural } };
      }
    }
    strings[key] = { extractionState: 'manual', localizations };
  }
  return `${JSON.stringify({ sourceLanguage: SOURCE_LOCALE, strings, version: '1.0' }, null, 2)}\n`;
}

function swiftIdentifier(key) {
  const parts = key.split(/[.\s_-]+/).filter(Boolean);
  return parts.map((part, index) => (index === 0 ? part[0].toLowerCase() + part.slice(1) : part[0].toUpperCase() + part.slice(1))).join('');
}

function swiftAccessor({ base }, ios) {
  const lines = [
    `// ${BANNER}`,
    '',
    'import Foundation',
    '',
    `${ios.access}enum ${ios.enumName} {`,
  ];
  for (const key of sortedKeys(base)) {
    const value = base.get(key);
    const name = swiftIdentifier(key);
    const order = orderFor(base, key);
    const doc = typeof value === 'string' ? value : value.other;
    lines.push(`    /// ${doc.replaceAll('\n', ' ')}`);
    if (isPlural(value)) {
      lines.push(`    ${ios.access}static func ${name}(_ count: Int) -> String { tr("${key}", count) }`);
    } else if (order.length === 0) {
      lines.push(`    ${ios.access}static var ${name}: String { tr("${key}") }`);
    } else {
      const params = order.map((arg) => `${arg}: ${INTEGER_PLACEHOLDERS.has(arg) ? 'Int' : 'String'}`).join(', ');
      lines.push(`    ${ios.access}static func ${name}(${params}) -> String { tr("${key}", ${order.join(', ')}) }`);
    }
  }
  lines.push(
    '',
    '    private static func tr(_ key: String, _ args: CVarArg...) -> String {',
    `        let format = NSLocalizedString(key, bundle: Bundle${ios.bundle}, comment: "")`,
    '        return args.isEmpty ? format : String(format: format, locale: Locale.current, arguments: args)',
    '    }',
    '}',
    '',
  );
  return lines.join('\n');
}

// Android ─────────────────────────────────────────────────────────────────────

function androidName(prefix, key) {
  const snake = key
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[.\s-]+/g, '_')
    .toLowerCase();
  return `${prefix}_${snake}`;
}

function androidEscape(text) {
  return text
    .replaceAll('\\', String.raw`\\`)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", String.raw`\'`)
    .replaceAll('"', String.raw`\"`)
    .replaceAll('\n', String.raw`\n`)
    .replace(/^([@?])/, String.raw`\$1`);
}

function androidFormat(text, order) {
  const formatted = order.length > 0;
  const escaped = androidEscape(formatted ? text.replaceAll('%', '%%') : text);
  return escaped.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_, name) => {
    const spec = INTEGER_PLACEHOLDERS.has(name) ? 'd' : 's';
    return `%${order.indexOf(name) + 1}$${spec}`;
  });
}

function stringsXml({ base, tables }, locale, prefix) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${BANNER} -->`, '<resources>'];
  for (const key of sortedKeys(base)) {
    const order = orderFor(base, key);
    const value = tables.get(locale).get(key);
    const name = androidName(prefix, key);
    if (typeof value === 'string') {
      const attrs = order.length === 0 && value.includes('%') ? ' formatted="false"' : '';
      lines.push(`    <string name="${name}"${attrs}>${androidFormat(value, order)}</string>`);
    } else {
      lines.push(`    <plurals name="${name}">`);
      for (const [quantity, text] of Object.entries(value)) {
        lines.push(`        <item quantity="${quantity}">${androidFormat(text, ['count'])}</item>`);
      }
      lines.push('    </plurals>');
    }
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

// ── tokens ───────────────────────────────────────────────────────────────────

function hex(value) {
  const match = /^#([0-9A-Fa-f]{6})$/.exec(value);
  if (!match) throw new Error(`tokens.json: ${value} is not a #RRGGBB colour`);
  return match[1].toUpperCase();
}

function capitalize(word) {
  return word[0].toUpperCase() + word.slice(1);
}

function tokensSwift(tokens) {
  const lines = [`// ${BANNER}`, '', 'import SwiftUI', '', 'public enum Tokens {'];
  for (const group of ['brand', 'status']) {
    lines.push(`    public enum ${capitalize(group)} {`);
    for (const [name, { light, dark }] of Object.entries(tokens[group])) {
      lines.push(`        public static let ${name} = Color(light: 0x${hex(light)}, dark: 0x${hex(dark)})`);
    }
    lines.push('    }');
  }
  for (const group of ['radius', 'spacing']) {
    lines.push(`    public enum ${capitalize(group)} {`);
    for (const [name, value] of Object.entries(tokens[group])) {
      lines.push(`        public static let ${name}: CGFloat = ${value}`);
    }
    lines.push('    }');
  }
  lines.push('}', '');
  return lines.join('\n');
}

function tokensKotlin(tokens) {
  const lines = [
    `// ${BANNER}`,
    '',
    'package org.weldsuite.ui',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    '',
    'object Tokens {',
  ];
  for (const group of ['brand', 'status']) {
    lines.push(`    object ${capitalize(group)} {`);
    for (const [name, { light, dark }] of Object.entries(tokens[group])) {
      lines.push(`        val ${name} = DayNight(Color(0xFF${hex(light)}), Color(0xFF${hex(dark)}))`);
    }
    lines.push('    }');
  }
  for (const group of ['radius', 'spacing']) {
    lines.push(`    object ${capitalize(group)} {`);
    for (const [name, value] of Object.entries(tokens[group])) {
      lines.push(`        val ${name} = ${value}.dp`);
    }
    lines.push('    }');
  }
  lines.push('}', '');
  return lines.join('\n');
}

// ── run ──────────────────────────────────────────────────────────────────────

function outputs() {
  const files = new Map();
  for (const entry of STRING_SOURCES) {
    const loaded = loadSource(entry.source);
    files.set(entry.ios.catalog, xcstrings(loaded));
    files.set(entry.ios.accessor, swiftAccessor(loaded, entry.ios));
    for (const locale of LOCALES) {
      const folder = locale === SOURCE_LOCALE ? 'values' : `values-${locale}`;
      files.set(`${entry.android.res}/${folder}/strings.xml`, stringsXml(loaded, locale, entry.android.prefix));
    }
  }
  const tokens = readJson(join(SHARED, 'tokens.json'));
  files.set('apps/ios/WeldKit/Sources/WeldUI/Generated/Tokens.swift', tokensSwift(tokens));
  files.set('apps/android/ui/src/main/kotlin/org/weldsuite/ui/Tokens.kt', tokensKotlin(tokens));
  for (const copy of OPENAPI_COPIES) {
    files.set(copy.to, readFileSync(join(SHARED, copy.from), 'utf8'));
  }
  return files;
}

function normalise(text) {
  return text.replaceAll('\r\n', '\n');
}

function main() {
  const check = process.argv.includes('--check');
  const files = outputs();
  const stale = [];
  for (const [relative, content] of files) {
    const path = join(ROOT, relative);
    const current = existsSync(path) ? normalise(readFileSync(path, 'utf8')) : null;
    if (current === content) continue;
    if (check) {
      stale.push(relative);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${relative}`);
  }
  if (check && stale.length > 0) {
    console.error(`Generated mobile files are out of date. Run \`pnpm mobile:generate\`:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  if (check) console.log(`${files.size} generated mobile files are up to date.`);
}

main();
